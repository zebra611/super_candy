"""客服用语的礼貌层（11-21）。

用户反馈原话："整体来说客服态度都没有毕恭毕敬的感觉，这个需要全盘改。"

为什么单独一层，而不逐句改配置：
    面向商家的句子散在 4 份场景配置 + 十几处代码兜底里，两百多条。逐句改会
    漏、会写成两套口径，下次改话术又回到原点。这里用一张**有序替换表**，
    在所有回复出话前统一润色：只动称呼与语气，不动事实、数字、材料名、热线，
    所以不会改变任何核对结论。

不改的三类（必须逐字，改了就丢依据）：
    - 官方 QA 原话（qa_hit / intent=qa / official_script）：转述就不叫原话；
    - 结束语（含"感谢您的接听/感谢您的配合"）：已经是官方口径；
    - 出错 / 空回复：要的是最短最确定。

边界约定：
    - "你们"不改（那是复数主体，不是敬称对象）；
    - 已经是"麻烦您报一下"的不再加"麻烦您"，避免叠词；
    - 单次顺序替换，不递归，防止 A→B→C 越改越长。
"""

import re

#: 有序替换表：(正则, 替换)。先长后短，避免"您说一声就行"被"说一声就行"先吃掉。
_RULES = (
    # 称呼：把"你"统一成"您"（"你们"是复数主体，不动）
    (re.compile(r"(?<!您)你(?!们)"), "您"),
    # 请求式：命令 → 敬语请求。先吃掉句中的"您"，再补"麻烦您"，
    # 否则"您报一下"会变成"您麻烦您报一下"（11-21 实测踩到）。
    (re.compile(r"您报一下"), "麻烦您报一下"),
    (re.compile(r"麻烦报一下"), "麻烦您报一下"),
    (re.compile(r"您说一下"), "麻烦您说一下"),
    (re.compile(r"您再说一遍"), "麻烦您再说一遍"),
    # 叠词兜底：任何"麻烦麻烦您 / 您麻烦您"都收敛成一次
    (re.compile(r"麻烦麻烦您"), "麻烦您"),
    (re.compile(r"您麻烦您"), "麻烦您"),
    (re.compile(r"请麻烦您"), "请您"),
    # 句尾语气：生硬的"就行/就行了" → "就好"
    (re.compile(r"说四个数字就行"), "说四个数字就好"),
    (re.compile(r"您说一声就行"), "您吩咐一声就好"),
    (re.compile(r"说一声就行"), "吩咐一声就好"),
    (re.compile(r"您先说"), "您请先说"),
    (re.compile(r"您直接说哪一步"), "您请说是哪一步"),
    (re.compile(r"别急"), "您别着急"),
    # "先别折腾"读起来像训人；客户说页面打不开时更不能这么讲
    (re.compile(r"先别折腾"), "您先别着急"),
    (re.compile(r"别折腾"), "您别费劲"),
    # 确认问句：加"您看"，把"考问"变成"请示"
    (re.compile(r"这样说明白了吗"), "您看这样说明白了吗"),
    (re.compile(r"您还有什么想具体了解的吗"), "您看还有哪里需要我说明的"),
    (re.compile(r"您清楚怎么提交吗"), "您看提交这一步还有不清楚的吗"),
)

#: 这些字样说明是官方口径/结束语，整句跳过润色。
_SKIP_MARKS = ("感谢您的接听", "感谢您的配合", "祝您生活愉快")


def polish(text, frozen=False):
    """把一句客服话术润成敬语口吻。frozen=True 时原样返回（官方原话/结束语）。"""
    s = str(text or "")
    if not s or frozen:
        return s
    if any(w in s for w in _SKIP_MARKS):
        return s
    for pattern, repl in _RULES:
        s = pattern.sub(repl, s)
    return s
